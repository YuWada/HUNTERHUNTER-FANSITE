for line in existing_content.split('\n'):
    if line.startswith('| 「'):
        quote = line.split('|')[1].strip()
        existing_quotes.append(quote)

# 被りを排除して追記
with open(file_path, "a", encoding="utf-8") as f:
    count = 0
    for q, vol, speaker, meaning in quotes:
        # 既存にあるか簡易チェック
        is_exist = False
