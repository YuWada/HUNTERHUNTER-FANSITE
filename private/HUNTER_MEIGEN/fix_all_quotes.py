md_path = "俺でなきゃ見逃しちゃう名台詞集.md"
with open(md_path, "r", encoding="utf-8") as f:
    content = f.read()

pre_table = []
for line in content.split('\n'):
    if line.strip().startswith('| セリフ'):
        break
    pre_table.append(line)

# Sort the new list just in case
import re
def extract_vol(vol_str):
    m = re.search(r'\d+', vol_str)
    return int(m.group()) if m else 9999

quotes_data.sort(key=lambda x: extract_vol(x['volume']))

md_out = "\n".join(pre_table) + "\n"
if not md_out.endswith('\n\n'):
    md_out += "\n"
md_out += "| セリフ | 登場巻・話数 | 発言者 | 意味 |\n"
md_out += "| --- | --- | --- | --- |\n"
for q in quotes_data:
    # Remove any stray internal line breaks
    quote = q['quote'].replace('\n', ' ')
    vol = q['volume']
    char = q['character']
    meaning = q['meaning'].replace('\n', ' ')
    md_out += f"| {quote} | {vol} | {char} | {meaning} |\n"

with open(md_path, "w", encoding="utf-8") as f:
    f.write(md_out)

